function __t($key, $placeholders = []) {
    global $translations;
    $lang = defined('APP_LANG') ? APP_LANG : 'pt-BR';
    $text = $translations[$lang][$key] ?? ($translations['pt-BR'][$key] ?? $key);
    foreach ($placeholders as $k => $v) {
        $text = str_replace('{' . $k . '}', $v, $text);
    }
    return htmlspecialchars($text, ENT_QUOTES, 'UTF-8');
}
